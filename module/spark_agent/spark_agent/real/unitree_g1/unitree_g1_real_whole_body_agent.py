    def _hand_state_sub_thread(self):
        while True:
            left_msg = self._left_hand_state_suber.Read()
            if left_msg is not None:
                self._set_monitored_hand_q(
                    "left",
                    self._hand_q_from_state_msg(left_msg, Dex3_1_Left_JointIndex),
                )
            right_msg = self._right_hand_state_suber.Read()
            if right_msg is not None:
                self._set_monitored_hand_q(
                    "right",
                    self._hand_q_from_state_msg(right_msg, Dex3_1_Right_JointIndex),
                )
            time.sleep(0.002)

    def _start_sub_threads(self):
        threading.Thread(target=self._state_sub_thread, daemon=True).start()
        if self.with_hand and self.enable_hand_state_monitor:
            threading.Thread(target=self._hand_state_sub_thread, daemon=True).start()

        cnt = 0
        while not self._low_state_buffer.GetData():
            time.sleep(0.1)
            cnt += 1
            if cnt % 10 == 0:
                print("Waiting to receive Unitree state data...")
            if cnt > 100:
                raise TimeoutError("Failed to receive Unitree state data.")

