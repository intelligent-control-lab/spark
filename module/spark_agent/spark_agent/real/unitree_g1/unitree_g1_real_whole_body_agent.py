    def _coerce_gripper_goal(self, goal_value, current_value: bool) -> bool:
        if goal_value is None:
            return bool(current_value)
        return bool(goal_value)

    def _resolve_hand_target(self, side: str, action_info: dict) -> np.ndarray:
        control_key = f"{side}_gripper_control"
        if control_key in action_info:
            target = np.asarray(action_info[control_key], dtype=float).reshape(-1)
            if target.size != Dex3_Num_Motors:
                raise ValueError(f"{control_key} must have {Dex3_Num_Motors} entries.")
            if side == "left":
                self.left_gripper_goal = bool(np.any(target > 1e-6))
                return np.clip(
                    target, self.left_hand_lower_joint_limit, self.left_hand_upper_joint_limit
                )
            self.right_gripper_goal = bool(np.any(target > 1e-6))
            return np.clip(
                target, self.right_hand_lower_joint_limit, self.right_hand_upper_joint_limit
            )

        goal_key = f"{side}_gripper_goal"
        if side == "left":
            self.left_gripper_goal = self._coerce_gripper_goal(
                action_info.get(goal_key, None), self.left_gripper_goal
            )
            target = self.left_hand_close_pos if self.left_gripper_goal else self.left_hand_open_pos
            return np.clip(
                target, self.left_hand_lower_joint_limit, self.left_hand_upper_joint_limit
            )

        self.right_gripper_goal = self._coerce_gripper_goal(
            action_info.get(goal_key, action_info.get("gripper_goal", None)),
            self.right_gripper_goal,
        )
        target = self.right_hand_close_pos if self.right_gripper_goal else self.right_hand_open_pos
        return np.clip(target, self.right_hand_lower_joint_limit, self.right_hand_upper_joint_limit)

    def _ctrl_dual_hand(self, left_q_target: np.ndarray, right_q_target: np.ndarray):
        for idx, joint_id in enumerate(Dex3_1_Left_JointIndex):
            self.left_hand_cmd_msg.motor_cmd[joint_id].q = float(left_q_target[idx])
        for idx, joint_id in enumerate(Dex3_1_Right_JointIndex):
            self.right_hand_cmd_msg.motor_cmd[joint_id].q = float(right_q_target[idx])
        if self.send_cmd:
            self._left_hand_cmd_pub.Write(self.left_hand_cmd_msg)
            self._right_hand_cmd_pub.Write(self.right_hand_cmd_msg)
        self._maybe_print_hand_command_debug(left_q_target, right_q_target)

    def _maybe_print_hand_command_debug(
        self, left_q_target: np.ndarray, right_q_target: np.ndarray
    ):
        if not self.hand_state_debug_print:
            return
        now = time.time()
        if now - self._last_hand_command_debug_time < 0.5:
            return
        self._last_hand_command_debug_time = now
        print(
            "[Dex3 hand command] "
            f"enabled={self.enable_hand_control} send_cmd={self.send_cmd} "
            f"left_goal={self.left_gripper_goal} right_goal={self.right_gripper_goal} "
            f"left_q={np.array2string(np.asarray(left_q_target), precision=3, suppress_small=True)} "
            f"right_q={np.array2string(np.asarray(right_q_target), precision=3, suppress_small=True)}"
        )

    def _send_control_hand(self, action_info: dict):
        if not self.enable_hand_control:
            return
        self.left_hand_q_target = self._resolve_hand_target("left", action_info)
        self.right_hand_q_target = self._resolve_hand_target("right", action_info)
        self._ctrl_dual_hand(self.left_hand_q_target, self.right_hand_q_target)

    def send_control(self, command: np.ndarray, **kwargs):
        action_info = kwargs.get("action_info", {})
        target_pos = self._clip_real_motor_target(
            self._coerce_real_motor_position_target(action_info)
        )
        target_vel = self._coerce_real_motor_velocity_target(action_info)
        kps, kds = self._gains_from_action_info(action_info)

        self.target_pos = target_pos.copy()
        self.target_vel = target_vel.copy()
        self.dof_pos_cmd = self._full_dof_from_real_motor_target(target_pos)
        self.dof_vel_cmd = self._full_dof_vel_from_real_motor_target(target_vel)
        self.dof_acc_cmd = np.zeros_like(self.dof_vel_cmd)

        self._send_control_hand(action_info)

        if self.send_cmd:
            self._set_motor_cmd(
                cmd_q=target_pos,
                cmd_dq=target_vel,
                cmd_tau=np.zeros(self.num_real_motor),
                cmd_kp=kps,
                cmd_kd=kds,
            )
            self._send_cmd(self.cmd_msg)

            control_period = self.dt * self.control_decimation
            current_control_timestamp = time.time()
            time_until_next_step = control_period - (
                current_control_timestamp - self.last_control_timestamp
            )
            if time_until_next_step > 0:
                time.sleep(time_until_next_step)
            self.last_control_timestamp = time.time()

    def get_feedback(self):
        ret = {}
        robot_base_frame = self._robot_base_frame_from_location_sources()
        ret["robot_base_frame"] = robot_base_frame

        real_robot_qpos = self.get_all_motor_q()
        real_robot_qvel = self.get_all_motor_dq()
        dof_pos_sensor_fbk = np.zeros(self.num_dof)
        dof_vel_sensor_fbk = np.zeros(self.num_dof)
        base_virtual_dof_values = self._base_virtual_dof_values(robot_base_frame)

        for dof in self.robot_cfg.DoFs:
            dof_idx = int(dof)
            if dof.name in base_virtual_dof_values:
                dof_pos_sensor_fbk[dof_idx] = base_virtual_dof_values[dof.name]
                if self.dof_vel_cmd is not None:
                    dof_vel_sensor_fbk[dof_idx] = self.dof_vel_cmd[dof_idx]
                continue

            real_dof = self._real_dof_for_robot_dof(dof)
            if real_dof is None:
                dof_pos_sensor_fbk[dof_idx] = self.robot_cfg.DefaultDoFVal[dof]
                continue

            dof_pos_sensor_fbk[dof_idx] = real_robot_qpos[real_dof]
            dof_vel_sensor_fbk[dof_idx] = real_robot_qvel[real_dof]

        dof_pos_sensor_fbk = self._overwrite_model_order_hand_feedback(dof_pos_sensor_fbk)
        self._maybe_print_hand_state_debug()

        ret["dof_pos_sensor_fbk"] = dof_pos_sensor_fbk.copy()
        ret["dof_vel_sensor_fbk"] = dof_vel_sensor_fbk.copy()

        if self.dof_pos_cmd is None:
            self.dof_pos_cmd = dof_pos_sensor_fbk.copy()
        if self.dof_vel_cmd is None:
            self.dof_vel_cmd = np.zeros(self.num_dof)
        if self.dof_acc_cmd is None:
            self.dof_acc_cmd = np.zeros(self.num_dof)

        ret["dof_pos_cmd"] = self.dof_pos_cmd
        ret["dof_vel_cmd"] = self.dof_vel_cmd
        ret["dof_acc_cmd"] = self.dof_acc_cmd

        dof_pos_fbk = self.dof_pos_cmd.copy()
        dof_pos_fbk = self._overwrite_base_virtual_dof_feedback(dof_pos_fbk, robot_base_frame)
        dof_pos_fbk = self._overwrite_model_order_hand_feedback(dof_pos_fbk)
        dof_vel_fbk = self.dof_vel_cmd.copy()

        ret["dof_pos_fbk"] = dof_pos_fbk
        ret["dof_vel_fbk"] = dof_vel_fbk
        ret["state"] = self._compose_cmd_state()

        twin = self.digital_twin
        if twin is None:
            ret["robot_goal_left_offset"] = self.left_goal_debug_frame.copy()
            ret["robot_goal_right_offset"] = self.right_goal_debug_frame.copy()
            ret["robot_goal_base_offset"] = self.base_goal_debug_frame.copy()
        else:
            ret["robot_goal_left_offset"] = twin.left_goal_debug_frame
