class UnitreeG1RealWholeBodyAgent(UnitreeG1RealSportModeAgent):
    """Real Unitree G1 low-level whole-body agent.

    This agent consumes joint-position targets generated by a policy such as
    UnitreeG1WBTPolicy. It keeps the transport, hand, digital-twin, and motor
    command plumbing from the legacy real WBT agent, but it does not run the
    WBT loco/squat neural policies inside the agent.
    """

    def __init__(self, robot_cfg: RobotConfig, **kwargs):
        self.body_robot_cfg_for_targets = UnitreeG1WholeBodyDynamic1Config()
        self.unitree_network_interface = kwargs.get(
            "unitree_network_interface", kwargs.get("net", "")
        )
        self.with_hand = "WithHand" in robot_cfg.__class__.__name__
        self.enable_hand_control = bool(kwargs.get("enable_hand_control", self.with_hand))
        self.enable_hand_state_monitor = bool(
            kwargs.get("enable_hand_state_monitor", self.with_hand)
        )
        self.hand_state_debug_print = bool(kwargs.get("hand_state_debug_print", False))
        self.hand_state_zero_invalid = bool(kwargs.get("hand_state_zero_invalid", True))
        if self.with_hand:
            self._init_hand_control(**kwargs)
        self._hand_state_lock = threading.Lock()
        self.left_hand_q_sensor = np.full(Dex3_Num_Motors, np.nan, dtype=float)
        self.right_hand_q_sensor = np.full(Dex3_Num_Motors, np.nan, dtype=float)
        self.left_hand_state_timestamp = None
        self.right_hand_state_timestamp = None
        self._last_hand_state_debug_time = 0.0
        self._last_hand_state_warn_time = 0.0
        self._last_hand_command_debug_time = 0.0
        self.left_gripper_goal = False
        self.right_gripper_goal = False
        self.left_gripper_debug_state = False
        self.right_gripper_debug_state = False
        self._init_real_robot_location_state(**kwargs)
        super().__init__(robot_cfg, **kwargs)
        self.enable_digital_twin = bool(kwargs.get("enable_digital_twin", True))
        self.digital_twin_backend = str(kwargs.get("digital_twin_backend", "mujoco"))
        self.digital_twin = None
        if self.enable_digital_twin:
            self._init_digital_twin(robot_cfg, **kwargs)
        self.last_control_timestamp = time.time()

    def _init_sport_mode(self):
        self.body_robot_cfg_for_targets = UnitreeG1WholeBodyDynamic1Config()
        self.default_dof_pos = self._default_real_motor_pos()
        self.default_pos_lower_body = self.default_dof_pos[:12].copy()
        self.target_pos = self.default_dof_pos.copy()
        self.target_vel = np.zeros_like(self.target_pos)

    def _default_real_motor_pos(self):
        default_pos = []
        for motor in self.robot_cfg.RealMotors:
            if hasattr(self.robot_cfg.DoFs, motor.name):
                dof = getattr(self.robot_cfg.DoFs, motor.name)
                default_pos.append(self.robot_cfg.DefaultDoFVal[dof])
            else:
                default_pos.append(0.0)
        return np.asarray(default_pos, dtype=float)

    def _default_full_dof_pos(self):
        return np.asarray(
            [self.robot_cfg.DefaultDoFVal[dof] for dof in self.robot_cfg.DoFs],
            dtype=float,
        )

    def _body_default_qpos(self):
        return np.asarray(
            [
                self.body_robot_cfg_for_targets.DefaultDoFVal[dof]
                for dof in self.body_robot_cfg_for_targets.DoFs
            ],
            dtype=float,
        )

    def _move_to_default_pos(self):
        print("Moving to default pos.")
        total_time = 2.0
        num_step = max(1, int(total_time / self.dt))
        self.default_dof_pos = self._default_real_motor_pos()
        init_dof_pos = self.get_real_motor_q()

        for i in range(num_step):
            alpha = i / num_step
            target = init_dof_pos * (1.0 - alpha) + self.default_dof_pos * alpha
            self._set_motor_cmd(
                cmd_q=target,
                cmd_dq=np.zeros(self.num_real_motor),
                cmd_tau=np.zeros(self.num_real_motor),
                cmd_kp=self.kps,
                cmd_kd=self.kds,
                weight=0.0,
            )
            if self.send_cmd:
                self._send_cmd(self.cmd_msg)
            print("Moving to default pos: {:.2f}%".format(alpha * 100), end="\r")
            time.sleep(self.dt)

        print("Enter default pos state.")
        print("Waiting for the Right_Start_Long signal...")

    def _target_from_dof_pos(self, target_dof_pos):
        target = np.asarray(target_dof_pos, dtype=float).reshape(-1)

        if target.shape[0] == self.num_real_motor:
            return target.copy()

        values = []
        if target.shape[0] == len(self.robot_cfg.DoFs):
            for motor in self.robot_cfg.RealMotors:
                if not hasattr(self.robot_cfg.DoFs, motor.name):
                    raise KeyError(f"No robot DoF named {motor.name}")
                values.append(target[int(getattr(self.robot_cfg.DoFs, motor.name))])
            return np.asarray(values, dtype=float)

        if target.shape[0] == len(self.body_robot_cfg_for_targets.DoFs):
            for motor in self.robot_cfg.RealMotors:
                if not hasattr(self.body_robot_cfg_for_targets.DoFs, motor.name):
                    raise KeyError(f"No whole-body DoF named {motor.name}")
                values.append(
                    target[int(getattr(self.body_robot_cfg_for_targets.DoFs, motor.name))]
                )
            return np.asarray(values, dtype=float)

        raise ValueError(
            "target_dof_pos must be full robot DoF position, canonical whole-body qpos, "
            f"or real motor position; got shape {target.shape}"
        )

    def _coerce_real_motor_position_target(self, action_info):
        if "target_actuated_pos" in action_info:
            target = np.asarray(action_info["target_actuated_pos"], dtype=float).reshape(-1)
            if target.shape[0] != self.num_real_motor:
                raise ValueError(
                    f"target_actuated_pos must have {self.num_real_motor} entries, got {target.shape[0]}"
                )
            return target.copy()

        if "target_dof_pos" in action_info:
            return self._target_from_dof_pos(action_info["target_dof_pos"])

        raise KeyError(
            "UnitreeG1RealWholeBodyAgent expects action_info['target_actuated_pos'] "
            "or action_info['target_dof_pos'] from a whole-body policy."
        )

    def _coerce_real_motor_velocity_target(self, action_info):
        if "target_actuated_vel" in action_info:
            target = np.asarray(action_info["target_actuated_vel"], dtype=float).reshape(-1)
        elif "target_dof_vel" in action_info:
            target = np.asarray(action_info["target_dof_vel"], dtype=float).reshape(-1)
        else:
            return np.zeros(self.num_real_motor, dtype=float)

        if target.shape[0] == self.num_real_motor:
            return target.copy()

        if target.shape[0] == len(self.robot_cfg.DoFs):
            values = []
            for motor in self.robot_cfg.RealMotors:
                if not hasattr(self.robot_cfg.DoFs, motor.name):
                    raise KeyError(f"No robot DoF named {motor.name}")
                values.append(target[int(getattr(self.robot_cfg.DoFs, motor.name))])
            return np.asarray(values, dtype=float)

        return np.zeros(self.num_real_motor, dtype=float)

    def _gains_from_action_info(self, action_info):
        kps = np.asarray(
            action_info.get("target_actuated_kps", action_info.get("motor_kps", self.kps)),
            dtype=float,
        ).reshape(-1)
        kds = np.asarray(
            action_info.get("target_actuated_kds", action_info.get("motor_kds", self.kds)),
            dtype=float,
        ).reshape(-1)
        if kps.shape[0] != self.num_real_motor:
            kps = np.asarray(self.kps, dtype=float)
        if kds.shape[0] != self.num_real_motor:
            kds = np.asarray(self.kds, dtype=float)
        return kps, kds

    def _clip_real_motor_target(self, target_pos):
        target_pos = np.asarray(target_pos, dtype=float).reshape(-1).copy()
        for idx, motor in enumerate(self.robot_cfg.RealMotors):
            joint_pos_min, joint_pos_max = self.robot_cfg.RealMotorPosLimit.get(
                motor, (-np.inf, np.inf)
            )
            target_pos[idx] = np.clip(target_pos[idx], joint_pos_min, joint_pos_max)
        return target_pos

    def _full_dof_from_real_motor_target(self, target_pos):
        if self.dof_pos_cmd is not None and len(self.dof_pos_cmd) == len(self.robot_cfg.DoFs):
            dof_pos = np.asarray(self.dof_pos_cmd, dtype=float).copy()
        else:
            dof_pos = self._default_full_dof_pos()

        for idx, motor in enumerate(self.robot_cfg.RealMotors):
            if hasattr(self.robot_cfg.DoFs, motor.name):
                dof_pos[int(getattr(self.robot_cfg.DoFs, motor.name))] = target_pos[idx]
        return dof_pos

    def _full_dof_vel_from_real_motor_target(self, target_vel):
        dof_vel = np.zeros(len(self.robot_cfg.DoFs), dtype=float)
        for idx, motor in enumerate(self.robot_cfg.RealMotors):
            if hasattr(self.robot_cfg.DoFs, motor.name):
                dof_vel[int(getattr(self.robot_cfg.DoFs, motor.name))] = target_vel[idx]
        return dof_vel

    def _body_feedback_from_full_dof(self, full_dof_pos, full_dof_vel):
        full_dof_pos = np.asarray(full_dof_pos, dtype=float).reshape(-1)
        full_dof_vel = np.asarray(full_dof_vel, dtype=float).reshape(-1)
        body_qpos = self._body_default_qpos()
        body_qvel = np.zeros(len(self.body_robot_cfg_for_targets.DoFs) - 1, dtype=float)
        try:
            body_qvel[3:6] = np.asarray(self.get_imu_gyroscope(), dtype=float).reshape(3)
        except Exception:
            pass

        for name in (
            "LinearX",
            "LinearY",
            "LinearZ",
            "QuaternionW",
            "QuaternionX",
            "QuaternionY",
            "QuaternionZ",
        ):
            if hasattr(self.robot_cfg.DoFs, name):
                body_qpos[int(getattr(self.body_robot_cfg_for_targets.DoFs, name))] = full_dof_pos[
                    int(getattr(self.robot_cfg.DoFs, name))
                ]

        for motor in self.robot_cfg.RealMotors:
            if not hasattr(self.body_robot_cfg_for_targets.DoFs, motor.name):
                continue
            body_qpos_idx = int(getattr(self.body_robot_cfg_for_targets.DoFs, motor.name))
            body_qvel_idx = body_qpos_idx - 1
            if hasattr(self.robot_cfg.DoFs, motor.name):
                dof_idx = int(getattr(self.robot_cfg.DoFs, motor.name))
                body_qpos[body_qpos_idx] = full_dof_pos[dof_idx]
                if 0 <= body_qvel_idx < body_qvel.shape[0] and dof_idx < full_dof_vel.shape[0]:
                    body_qvel[body_qvel_idx] = full_dof_vel[dof_idx]

        return body_qpos, body_qvel

    def _init_real_robot_location_state(self, **kwargs):
        self.real_robot_location_topic = kwargs.get(
            "real_robot_location_topic", "/real_robot_location"
        )
        self.real_robot_location_enabled = bool(kwargs.get("real_robot_location_enabled", False))
        self.real_robot_location_timeout = float(kwargs.get("real_robot_location_timeout", 0.5))
        self.real_robot_location_orientation_source = str(
            kwargs.get("real_robot_location_orientation_source", "topic")
        ).lower()
        self.real_robot_location_align_imu_to_pose = bool(
            kwargs.get("real_robot_location_align_imu_to_pose", False)
        )
        self.real_robot_location_filter_alpha = float(
            kwargs.get("real_robot_location_filter_alpha", 1.0)
        )
        self.default_robot_base_height = 0.793
        self._real_robot_location_lock = threading.Lock()
        self._real_robot_location_T = None
        self._real_robot_location_timestamp = None
        self._imu_world_rotation_correction = None
        self._real_robot_location_sub = None
        self._last_real_robot_location_warn_time = 0.0
        self._last_robot_base_frame = np.eye(4, dtype=np.float64)
        self._last_robot_base_frame[2, 3] = self.default_robot_base_height

    def attach_ros1_real_robot_location(self, rospy_module, msg_type):
        if not self.real_robot_location_enabled or not self.real_robot_location_topic:
            return False
        if self._real_robot_location_sub is not None:
            return True
        self._real_robot_location_sub = rospy_module.Subscriber(
            self.real_robot_location_topic,
            msg_type,
            self._real_robot_location_callback,
        )
        print(f"Subscribing to real robot location topic: {self.real_robot_location_topic}")
        return True

    def attach_ros2_real_robot_location(self, node, msg_type, qos):
        if not self.real_robot_location_enabled or not self.real_robot_location_topic:
            return False
        if self._real_robot_location_sub is not None:
            return True
        self._real_robot_location_sub = node.create_subscription(
            msg_type,
            self.real_robot_location_topic,
            self._real_robot_location_callback,
            qos,
        )
        print(f"Subscribing to real robot location topic: {self.real_robot_location_topic}")
        return True

    def _warn_real_robot_location_throttle(self, message):
        now = time.time()
        if now - self._last_real_robot_location_warn_time > 1.0:
            print(message)
            self._last_real_robot_location_warn_time = now

    def _real_robot_location_callback(self, msg):
        values = np.asarray(msg.data, dtype=np.float64).reshape(-1)
        if values.size < 16:
            self._warn_real_robot_location_throttle(
                f"{self.real_robot_location_topic} expects at least 16 values, got {values.size}"
            )
            return

        robot_location = values[:16].reshape(4, 4)
        if not np.all(np.isfinite(robot_location)):
            self._warn_real_robot_location_throttle(
                f"{self.real_robot_location_topic} contains non-finite values"
            )
            return

        robot_location = robot_location.copy()
        robot_location[3, :] = np.array([0.0, 0.0, 0.0, 1.0], dtype=np.float64)
        alpha = np.clip(self.real_robot_location_filter_alpha, 0.0, 1.0)
        with self._real_robot_location_lock:
            if self._real_robot_location_T is not None and alpha < 1.0:
                robot_location[:3, 3] = (
                    alpha * robot_location[:3, 3]
                    + (1.0 - alpha) * self._real_robot_location_T[:3, 3]
                )
            self._real_robot_location_T = robot_location
            self._real_robot_location_timestamp = time.time()
            if (
                self.real_robot_location_align_imu_to_pose
                and self._imu_world_rotation_correction is None
            ):
                imu_rotation = self._imu_rotation_matrix()
                self._imu_world_rotation_correction = robot_location[:3, :3] @ imu_rotation.T

    def _latest_real_robot_location(self):
        with self._real_robot_location_lock:
            if self._real_robot_location_T is None or self._real_robot_location_timestamp is None:
                return None, None
            return (
                self._real_robot_location_T.copy(),
                time.time() - self._real_robot_location_timestamp,
            )

    def _normalized_imu_quaternion(self):
        try:
            imu_q = np.asarray(self.get_imu_quaternion(), dtype=np.float64).reshape(4)
        except Exception:
            return np.array([1.0, 0.0, 0.0, 0.0], dtype=np.float64)
        norm = float(np.linalg.norm(imu_q))
        if norm > 1e-12:
            return imu_q / norm
        return np.array([1.0, 0.0, 0.0, 0.0], dtype=np.float64)

    def _imu_rotation_matrix(self):
        imu_q = self._normalized_imu_quaternion()
        return R.from_quat([imu_q[1], imu_q[2], imu_q[3], imu_q[0]]).as_matrix()

    def _world_aligned_imu_rotation_matrix(self):
        imu_rotation = self._imu_rotation_matrix()
        with self._real_robot_location_lock:
            correction = None
            if self._imu_world_rotation_correction is not None:
                correction = self._imu_world_rotation_correction.copy()
        if correction is None:
            return imu_rotation
        return correction @ imu_rotation

    def _fallback_robot_base_frame(self):
        robot_base_frame = np.eye(4, dtype=np.float64)
        robot_base_frame[2, 3] = self.default_robot_base_height
        robot_base_frame[:3, :3] = self._world_aligned_imu_rotation_matrix()
        return robot_base_frame

    def _robot_base_frame_from_location_sources(self):
        robot_base_frame = None
        if self.real_robot_location_enabled:
            real_robot_location, location_age = self._latest_real_robot_location()
            if real_robot_location is None:
                self._warn_real_robot_location_throttle(
                    f"Waiting for real robot location on {self.real_robot_location_topic}"
                )
            elif location_age is not None and location_age > self.real_robot_location_timeout:
                self._warn_real_robot_location_throttle(
                    f"Real robot location is stale ({location_age:.3f}s); holding previous base frame"
                )
                robot_base_frame = self._last_robot_base_frame.copy()
            else:
                robot_base_frame = real_robot_location

        if robot_base_frame is None:
            robot_base_frame = self._fallback_robot_base_frame()
        if self.real_robot_location_orientation_source in ("imu", "robot_imu"):
            robot_base_frame[:3, :3] = self._world_aligned_imu_rotation_matrix()
        robot_base_frame[3, :] = np.array([0.0, 0.0, 0.0, 1.0], dtype=np.float64)
        self._last_robot_base_frame = robot_base_frame.copy()
        return robot_base_frame

    def _base_frame_to_mujoco_quaternion(self, robot_base_frame):
        quat_xyzw = R.from_matrix(robot_base_frame[:3, :3]).as_quat()
        return np.array([quat_xyzw[3], quat_xyzw[0], quat_xyzw[1], quat_xyzw[2]], dtype=np.float64)

    def _base_virtual_dof_values(self, robot_base_frame):
        quat_wxyz = self._base_frame_to_mujoco_quaternion(robot_base_frame)
        euler_xyz = R.from_matrix(robot_base_frame[:3, :3]).as_euler("xyz", degrees=False)
        return {
            "LinearX": float(robot_base_frame[0, 3]),
            "LinearY": float(robot_base_frame[1, 3]),
            "LinearZ": float(robot_base_frame[2, 3]),
            "QuaternionW": float(quat_wxyz[0]),
            "QuaternionX": float(quat_wxyz[1]),
            "QuaternionY": float(quat_wxyz[2]),
            "QuaternionZ": float(quat_wxyz[3]),
            "RotPitch": float(euler_xyz[1]),
            "RotYaw": float(euler_xyz[2]),
        }

    def _overwrite_base_virtual_dof_feedback(self, dof_pos, robot_base_frame):
        base_values = self._base_virtual_dof_values(robot_base_frame)
        for dof in self.robot_cfg.DoFs:
            if dof.name in base_values:
                dof_pos[int(dof)] = base_values[dof.name]
        return dof_pos

    def _real_dof_for_robot_dof(self, dof):
        if dof in self.robot_cfg.DoF_to_RealDoF:
            return self.robot_cfg.DoF_to_RealDoF[dof]
        if hasattr(self.robot_cfg, "RealDoFs") and hasattr(self.robot_cfg.RealDoFs, dof.name):
            return getattr(self.robot_cfg.RealDoFs, dof.name)
        return None

    def _init_digital_twin(self, robot_cfg: RobotConfig, **kwargs):
        if self.digital_twin_backend != "mujoco":
            raise ValueError("The Unitree real-agent digital twin currently supports MuJoCo only")
        import mujoco

        from spark_agent.simulation.mujoco.unitree_g1.unitree_g1_whole_body_mujoco_agent import (
            UnitreeG1WholeBodyMujocoAgent,
        )

        kwargs["enable_viewer"] = True
        self.digital_twin = UnitreeG1WholeBodyMujocoAgent(robot_cfg, **kwargs)
        bit = int(mujoco.mjtDisableBit.mjDSBL_CONTACT)
        self.digital_twin.model.opt.disableflags |= bit
        mujoco.mj_forward(self.digital_twin.model, self.digital_twin.data)
        self._digital_twin_sync_enabled = True
        threading.Thread(
            target=self._digital_twin_sync_thread,
            kwargs={"sync_hz": kwargs.get("digital_twin_sync_hz", 500.0)},
            daemon=True,
        ).start()

    def _latest_monitored_hand_q(self, side: str):
        with self._hand_state_lock:
            if side == "left":
                if self.left_hand_state_timestamp is None:
                    return None
                return self.left_hand_q_sensor.copy()
            if self.right_hand_state_timestamp is None:
                return None
            return self.right_hand_q_sensor.copy()

    def _warn_hand_state_throttle(self, message):
        now = time.time()
        if now - self._last_hand_state_warn_time > 1.0:
            print(message)
            self._last_hand_state_warn_time = now

    def _set_monitored_hand_q(self, side: str, values: np.ndarray):
        values = np.asarray(values, dtype=float).reshape(Dex3_Num_Motors)
        if self.hand_state_zero_invalid and np.allclose(values, 0.0, atol=1.0e-8):
            self._warn_hand_state_throttle(
                f"Ignoring all-zero Dex3 {side} hand state; waiting for valid rt/dex3/{side}/state data"
            )
            return
        with self._hand_state_lock:
            if side == "left":
                self.left_hand_q_sensor = values.copy()
                self.left_hand_state_timestamp = time.time()
            else:
                self.right_hand_q_sensor = values.copy()
                self.right_hand_state_timestamp = time.time()

    def _model_order_hand_feedback(self) -> tuple[np.ndarray, np.ndarray]:
        left_target = self._latest_monitored_hand_q("left")
        right_target = self._latest_monitored_hand_q("right")
        if left_target is None:
            left_target = getattr(self, "left_hand_q_target", np.zeros(Dex3_Num_Motors))
        if right_target is None:
            right_target = getattr(self, "right_hand_q_target", np.zeros(Dex3_Num_Motors))
        return (
            np.asarray(left_target, dtype=float).reshape(Dex3_Num_Motors),
            np.asarray(right_target, dtype=float).reshape(Dex3_Num_Motors),
        )

    def _maybe_print_hand_state_debug(self):
        if not self.hand_state_debug_print:
            return
        now = time.time()
        if now - self._last_hand_state_debug_time < 1.0:
            return
        self._last_hand_state_debug_time = now
        with self._hand_state_lock:
            left_raw = (
                None if self.left_hand_state_timestamp is None else self.left_hand_q_sensor.copy()
            )
            right_raw = (
                None if self.right_hand_state_timestamp is None else self.right_hand_q_sensor.copy()
            )
            left_age = (
                None
                if self.left_hand_state_timestamp is None
                else now - self.left_hand_state_timestamp
            )
            right_age = (
                None
                if self.right_hand_state_timestamp is None
                else now - self.right_hand_state_timestamp
            )
        left_model, right_model = self._model_order_hand_feedback()
        left_source = "sensor" if left_raw is not None else "fallback"
        right_source = "sensor" if right_raw is not None else "fallback"

        def fmt(values):
            if values is None:
                return "None"
            return np.array2string(np.asarray(values), precision=3, suppress_small=True)

        def fmt_age(age):
            return "None" if age is None else f"{age:.3f}s"

        print(
            "[Dex3 hand monitor] "
            f"left={left_source} age={fmt_age(left_age)} raw={fmt(left_raw)} model={fmt(left_model)} | "
            f"right={right_source} age={fmt_age(right_age)} raw={fmt(right_raw)} model={fmt(right_model)}"
        )

    def _overwrite_model_order_hand_feedback(self, dof_pos: np.ndarray) -> np.ndarray:
        dof_pos = np.asarray(dof_pos, dtype=float).copy()
        if not (self.with_hand and dof_pos.shape[0] >= 50):
            return dof_pos
        left_hand, right_hand = self._model_order_hand_feedback()
        dof_pos[29:36] = left_hand
        dof_pos[43:50] = right_hand
        return dof_pos

    def _try_sync_digital_twin_once(self) -> bool:
        if getattr(self, "digital_twin", None) is None:
            return False
        if getattr(self, "_low_state_buffer", None) is None:
            return False
        if self._low_state_buffer.GetData() is None:
            return False

        qpos = self.digital_twin.data.qpos.copy()
        base_T = self._robot_base_frame_from_location_sources()
        qpos[0:3] = base_T[:3, 3]
        qpos[3:7] = self._base_frame_to_mujoco_quaternion(base_T)

        real_q_all = self.get_all_motor_q()
        qpos[7:22] = real_q_all[:15]
        qpos[22:29] = real_q_all[15:22]
        qpos[36:43] = real_q_all[22:29]
        if self.with_hand and qpos.shape[0] >= 50:
            left_hand, right_hand = self._model_order_hand_feedback()
            qpos[29:36] = left_hand
            qpos[43:50] = right_hand

        self.robot_base_goal = base_T @ self.digital_twin.base_goal_debug_frame
        self.digital_twin._set_dof_pos(qpos)
        self.digital_twin._post_control_processing()
        self.digital_twin.render_sphere(
            self.robot_base_goal[:3, 3],
            np.eye(3),
            0.1 * np.ones(3),
            [48 / 255, 245 / 255, 93 / 255, 0.3],
        )
        self.digital_twin.render_coordinate_frame(self.robot_base_goal, 0.2)
        self.digital_twin.viewer.sync()
        self.digital_twin.renderer.update_scene(self.digital_twin.data)
        return True

    def _digital_twin_sync_thread(self, sync_hz: float = 200.0) -> None:
        period = 1.0 / float(sync_hz)
        while True:
            if getattr(self, "_digital_twin_sync_enabled", True):
                try:
                    self._try_sync_digital_twin_once()
                except Exception:
                    pass
            time.sleep(period)

