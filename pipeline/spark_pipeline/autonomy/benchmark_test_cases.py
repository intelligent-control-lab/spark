LEGACY_TEST_CASE_ALIASES = MappingProxyType(
    {
        "random_arm_nominal": "arm_goal_static_v0",
        "arm_goal_static_sparse": "arm_goal_static_v1",
        "arm_goal_dynamic_sparse": "arm_goal_static_v1",
        "arm_goal_static_dense": "arm_goal_static_v2",
        "whole_goal_static_sparse": "whole_goal_static_v1",
        "whole_goal_dynamic_sparse": "whole_goal_static_v1",
        "whole_goal_static_dense": "whole_goal_static_v2",
        "whole_goal_dynamic_dense": "whole_goal_static_v2",
    }
)


def resolve_benchmark_test_case(name: str) -> BenchmarkTestCase:
    canonical = LEGACY_TEST_CASE_ALIASES.get(name, name)
    legacy = re.fullmatch(
        r"(?:AgiBotG1|FanucLRMate200iD|GalaxeaR1Lite|KinovaGen3|KukaIIWA14|UnitreeG1)"
        r"(?:FixedBase|MobileBase|WholeBody|SportMode|DualArm|RightArm|SingleArm)"
        r"_D[12]_(AG|WG)_(?:SO|DO)_v([01])",
        canonical,
    )
    if legacy:
        goal_kind = "arm_goal" if legacy.group(1) == "AG" else "whole_goal"
        # Historical v0/v1 meant sparse/dense.  Preserve those semantics while
        # the canonical v0/v1/v2 taxonomy means none/sparse/dense.
        level = "v1" if legacy.group(2) == "0" else "v2"
        canonical = f"{goal_kind}_static_{level}"
    try:
        case = TEST_CASES[canonical]
    except KeyError as exc:
        raise ValueError(
            f"Unknown benchmark test case {name!r}; choose: {', '.join(TEST_CASES)}"
        ) from exc
    forbidden = _FORBIDDEN_TASK_KEYS.intersection(case.task)
    if forbidden:
        raise ValueError(f"Task case {canonical!r} contains runner keys: {sorted(forbidden)}")
    return case


def apply_benchmark_test_case(cfg, name: str):
    case = resolve_benchmark_test_case(name)
    for key, value in case.parameters().items():
        setattr(cfg.env.task, key, value)
    cfg.env.task.task_name = case.name
    return cfg


def list_benchmark_test_cases() -> tuple[str, ...]:
    return tuple(TEST_CASES)
